def _fmt_craft(craft: CraftDescription) -> str:
    """工艺标准（应然）—— 三种维度分开列。"""
    lines: list[str] = []
    for proc in craft.processes:
        lines.append(f"### 工序：{proc}")
        c = craft.craft.get(proc)
        s = craft.standard.get(proc)
        e = craft.equipment.get(proc)
        lines.append(f"- 工艺描述：{c if c else '（台账无相关数据）'}")
        lines.append(f"- 标准参数：{s if s else '（台账无相关数据）'}")
        lines.append(f"- 设备描述：{e if e else '（台账无相关数据）'}")
        lines.append("")
    return "\n".join(lines)


def _fmt_ledger(ledger: Sequence[LedgerBatch]) -> str:
    """近期台账（实然）—— 逐批列，只列非空字段。

    批数由调用方限制；台账有 1200+ 行，全喂会撑爆上下文。
    """
    if not ledger:
        return "（台账无相关数据）"
    lines: list[str] = []
    for b in ledger:
        head = f"### 批次 {b.batch}" if b.batch else "### 批次（无批号）"
        lines.append(head)
        for k, v in b.values.items():
            lines.append(f"- {k}：{v}")
        lines.append("")
    return "\n".join(lines)


def build_user_prompt(
    product: str,
    craft: CraftDescription,
    ledger: Sequence[LedgerBatch],
    ledger_stats: stats_mod.LedgerStats | None = None,
) -> str:
    """构造用户消息。

    `ledger_stats` 由 `stats.analyze()` 算好传入 —— **不要在提示词里让模型自己算**，
    模型看 30 批原始数字是算不出相关系数的，只会写「可能有关」。
    """
    stats_block = (
        stats_mod.render(ledger_stats)
        if ledger_stats is not None
        else "（本轮未提供统计，只能基于逐批数据定性描述）"
    )

    return f"""分析产品：**{product}**

以下是该产品的**工序清单**（{len(craft.processes)} 道）：
{json.dumps(craft.processes, ensure_ascii=False)}

要求：**每一道工序都出一条**，不要漏、不要多、`name` 必须与上面逐字一致。

---

## 一、工艺标准（应然）

{_fmt_craft(craft)}

---

## 二、参数与收率的统计（服务端已算好，直接引用，不要自己重算）

{stats_block}

---

## 三、近期生产台账（实然，最近 {len(ledger)} 批）

{_fmt_ledger(ledger)}

---

现在逐工序分析。每条都要有 **`suggestions` 数组**（至少一条），
`suggestion.action` 必须能让车间照着做：参数名 + 目标值/范围 + 执行方式。
数据不足时，动作就是「补录哪个字段、补多少批」。

记住：**没有依据的话不说，但该给的建议要给。**
只输出 JSON。
"""
